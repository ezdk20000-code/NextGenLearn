export type ModuleLevel = 'Новичок' | 'Практик' | 'Специалист' | 'Эксперт'

/** Движки лабораторий. Один движок обслуживает много лабораторий. */
export type Engine =
  | 'logic' // симулятор логических схем: вентили, провода, таблицы истинности
  | 'hdl' // HDL-песочница Nand2Tetris: описываешь чип — тесты проверяют
  | 'cpu' // эмулятор процессора: регистры, память, пошаговое выполнение
  | 'stepper' // пошаговый симулятор протокола/алгоритма
  | 'params' // ползунки → модель → график
  | 'builder' // конструктор: собрать объект из частей
  | 'scenario' // ветвящийся кейс с решениями
  | 'code' // песочница кода с автотестами
  | 'sql' // SQL-песочница с учебной базой
  | 'graph' // визуализатор графов и алгоритмов на них
  | 'packet' // разбор пакетов «как в Wireshark»
  | 'crypto' // криптографическая мастерская

